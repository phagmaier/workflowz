import { type DragEvent, type FormEvent, useEffect, useRef, useState } from "react";
import { useConnection } from "../connection.tsx";
import { createSession, newDraftKey } from "../editor-session.ts";
import { editorHref } from "../route.ts";
import { UploadIcon } from "./icons.tsx";
import { Feedback, type FeedbackState, useDraft } from "./ui.tsx";

const MAX_BYTES = 1024 * 1024;

/**
 * Drop zone on the Workflows page. Imports text into a new tab-local draft; validation and
 * saving still belong to the daemon. `focused` is set when the page was opened to import.
 */
export function ImportPanel({ focused }: { focused: boolean }) {
  const { read, online } = useConnection();
  const [folder, setFolder] = useDraft("import:folder");
  const [file, setFile] = useState<File | null>(null);
  const [dragging, setDragging] = useState(false);
  const [feedback, setFeedback] = useState<FeedbackState>(null);
  const input = useRef<HTMLInputElement>(null);
  const folderInput = useRef<HTMLInputElement>(null);
  // Leaving or cancelling changes the generation, so a late reply never navigates away.
  const generation = useRef(0);
  const pending = useRef(false);
  useEffect(
    () => () => {
      generation.current += 1;
    },
    [],
  );
  // Runs before the frame's heading focus, which then leaves this choice alone.
  useEffect(() => {
    if (focused) input.current?.focus();
  }, [focused]);

  const choose = (chosen: File | undefined) => {
    if (!chosen) return;
    setFile(chosen);
    setFeedback(
      chosen.size > MAX_BYTES
        ? { kind: "error", text: "Workflow file exceeds 1 MiB. Choose a smaller file." }
        : null,
    );
  };
  const drop = (event: DragEvent<HTMLElement>) => {
    event.preventDefault();
    setDragging(false);
    choose(event.dataTransfer.files[0]);
    // Dropping isn't a focus change; move on to the next thing to fill in.
    queueMicrotask(() => folderInput.current?.focus());
  };

  const submit = async (event: FormEvent<HTMLFormElement>) => {
    event.preventDefault();
    if (pending.current || !file) return;
    const directory = folder.trim();
    if (!directory.startsWith("/")) {
      setFeedback({ kind: "error", text: "Enter the full workflow folder path, starting with /." });
      folderInput.current?.focus();
      return;
    }
    if (file.size > MAX_BYTES) {
      setFeedback({
        kind: "error",
        text: "Workflow file exceeds 1 MiB. Choose a smaller file.",
      });
      input.current?.focus();
      return;
    }
    pending.current = true;
    const mine = generation.current;
    setFeedback({ kind: "pending", text: "Reading and checking the file…" });
    let text: string;
    try {
      text = await file.text();
    } catch {
      pending.current = false;
      if (generation.current === mine)
        setFeedback({ kind: "error", text: "The file couldn't be read. Choose it again." });
      return;
    }
    const key = newDraftKey();
    const session = createSession(key, "new", directory);
    session.read = read;
    await session.open(text);
    // Even unreadable YAML or an unavailable daemon must leave the imported text editable.
    const visual = session.current && !!session.state.model;
    if (!visual) session.set({ mode: "text" });
    pending.current = false;
    // A cancelled import stays listed under unsaved drafts instead.
    if (generation.current === mine)
      window.location.hash = editorHref({ kind: "draft", key }, visual ? "map" : "yaml");
  };
  const cancel = () => {
    generation.current += 1;
    setFile(null);
    setFeedback(null);
    if (input.current) input.current.value = "";
    if (focused) window.location.hash = "#/workflows";
    else input.current?.focus();
  };

  return (
    <section
      className={`dropzone ${dragging ? "dragging" : ""} ${focused || file ? "open" : ""}`}
      aria-labelledby="import-title"
      onDragEnter={(event) => {
        event.preventDefault();
        setDragging(true);
      }}
      onDragOver={(event) => event.preventDefault()}
      onDragLeave={(event) => {
        if (!event.currentTarget.contains(event.relatedTarget as Node | null)) setDragging(false);
      }}
      onDrop={drop}
    >
      <div className="dropzone-head">
        <span className="dropzone-icon">
          <UploadIcon size={20} />
        </span>
        <div className="dropzone-text">
          <h2 id="import-title">Import a workflow file</h2>
          <p className="muted">
            Drop a YAML workflow here, written by you or generated by an agent. It opens as a draft
            with its text and comments intact. Nothing is saved or run until you choose.
          </p>
        </div>
        <label className="btn file-btn">
          {file ? "Choose another file…" : "Choose file…"}
          <input
            ref={input}
            className="file-input"
            type="file"
            accept=".yaml,.yml,text/yaml"
            aria-label="Workflow YAML file"
            onChange={(event) => choose(event.target.files?.[0])}
          />
        </label>
      </div>
      {file ? (
        <form className="dropzone-form" onSubmit={(event) => void submit(event)}>
          <p className="chosen">
            Chosen file: <strong className="mono">{file.name}</strong>
          </p>
          <div className="block">
            <label htmlFor="import-folder">Workflow folder</label>
            <input
              ref={folderInput}
              id="import-folder"
              name="folder"
              className="mono"
              value={folder}
              onChange={(event) => setFolder(event.target.value)}
              placeholder="/home/you/project/workflows"
              aria-describedby="import-folder-hint"
              required
            />
            <span id="import-folder-hint" className="hint">
              Paste the full path of the folder this file came from. Browsers can't see where a
              chosen file lives. Project and checklist paths in the file are resolved from here.
            </span>
          </div>
          <div className="row">
            <button
              className="btn btn-primary"
              type="submit"
              disabled={!online || feedback?.kind === "pending"}
            >
              Open draft
            </button>
            <button className="btn btn-quiet" type="button" onClick={cancel}>
              Cancel
            </button>
            <Feedback value={feedback} />
          </div>
        </form>
      ) : null}
    </section>
  );
}
